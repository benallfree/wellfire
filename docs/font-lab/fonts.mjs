const dir = new URL('./out/', import.meta.url)
mkdirSync(dir, { recursive: true })
const fonts = { readable, display }
writeFileSync(new URL('fonts.json', dir), JSON.stringify(fonts, null, 2) + '\n')
// Each font alone too, so measure.sh can price them separately.
for (const name in fonts) writeFileSync(new URL(`fonts-${name}.json`, dir), JSON.stringify(fonts[name], null, 2) + '\n')

// The preview inlines the fonts and the renderer so it opens from file:// with nothing else.
const renderer = readFileSync(new URL('./renderers/fonts.js', import.meta.url), 'utf8')
const page = readFileSync(new URL('./fonts-preview.html', import.meta.url), 'utf8')
  .replace('/*FONTS*/', `const fonts = ${JSON.stringify(fonts)}`)
  .replace('/*RENDERER*/', renderer.replace(/^const fonts.*\n/m, ''))
writeFileSync(new URL('fonts-preview.html', dir), page)
